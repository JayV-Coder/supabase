-- Recursos ativáveis e planos (v0.51.0). Cada funcionalidade do app que pode
-- ser ligada ou desligada tem uma linha em `features`; o admin do sistema a
-- desliga para todo mundo (`enabled`) e escolhe em quais planos ela entra
-- (`plan_features`). Quem usa recebe os recursos do plano da assinatura
-- ativa no Stripe ou, sem assinatura, os do plano padrão.
--
-- O plano padrão nasce com todos os recursos: ninguém perde o que já usa no
-- dia da migração. O admin tira dele o que quiser vender nos outros planos.
--
-- Leitura do catálogo e dos planos por RLS (todo mundo logado lê); escrita só
-- pelas RPCs `admin_*`, que conferem `is_admin()`. As assinaturas só
-- são escritas pela função `stripe-webhook`, com a service role.

-- 1. O admin do sistema é o mesmo que já edita textos e perguntas do Jev:
-- `public.admins` / `is_admin()`. Não há tela para nomear; entra pelo SQL
-- Editor do Supabase (`insert into public.admins (user_id) values
-- ('<uuid do auth.users>')`).
create function public.admin_require() returns void language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'admin.forbidden'; end if;
end;
$$;
revoke execute on function public.admin_require() from public, anon, authenticated;

-- 2. O catálogo. A chave é a do app (`organizations`, `secondOpinion`...); o
-- nome e a descrição vêm do i18n (`feature.<chave>.title` / `.detail`).
create table public.features (
  key text primary key check (key ~ '^[a-z][A-Za-z0-9]{1,40}$'),
  enabled boolean not null default true,
  position integer not null default 0,
  updated_by uuid references auth.users on delete set null,
  updated_at timestamptz not null default now()
);
alter table public.features enable row level security;
create policy "todos leem" on public.features for select to authenticated using (true);

-- 3. Os planos. Nome e descrição são dado do admin, como o nome de uma
-- organização; o preço só serve para a tela mostrar — quem cobra é o preço
-- do Stripe em `stripe_price_id`.
create table public.plans (
  key text primary key check (key ~ '^[a-z][a-z0-9_-]{1,30}$'),
  name text not null check (char_length(btrim(name)) between 1 and 60),
  description text not null default '' check (char_length(description) <= 300),
  position integer not null default 0,
  active boolean not null default true,
  is_default boolean not null default false,
  stripe_price_id text check (stripe_price_id ~ '^price_[A-Za-z0-9]{6,80}$'),
  price_cents integer check (price_cents >= 0),
  currency text check (currency ~ '^[a-z]{3}$'),
  billing_interval text check (billing_interval in ('month', 'year')),
  updated_by uuid references auth.users on delete set null,
  updated_at timestamptz not null default now(),
  -- O padrão é gratuito e sempre ativo: é o que vale para quem não assina.
  check (not is_default or (active and stripe_price_id is null))
);
create unique index plans_one_default on public.plans (is_default) where is_default;
create unique index plans_price on public.plans (stripe_price_id) where stripe_price_id is not null;
alter table public.plans enable row level security;
create policy "todos leem" on public.plans for select to authenticated using (true);

create table public.plan_features (
  plan_key text not null references public.plans on update cascade on delete cascade,
  feature_key text not null references public.features on delete cascade,
  primary key (plan_key, feature_key)
);
alter table public.plan_features enable row level security;
create policy "todos leem" on public.plan_features for select to authenticated using (true);

-- 4. Cliente e assinatura no Stripe. Uma assinatura por conta: a função
-- `billing` manda para o portal quem já assina, em vez de abrir outra.
create table public.billing_customers (
  user_id uuid primary key references auth.users on delete cascade,
  stripe_customer_id text not null unique,
  created_at timestamptz not null default now()
);
alter table public.billing_customers enable row level security;
create policy "lê a própria linha" on public.billing_customers for select to authenticated
  using (user_id = (select auth.uid()));

create table public.subscriptions (
  user_id uuid primary key references auth.users on delete cascade,
  plan_key text references public.plans on update cascade on delete set null,
  stripe_subscription_id text not null unique,
  stripe_price_id text,
  status text not null,
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  updated_at timestamptz not null default now()
);
alter table public.subscriptions enable row level security;
create policy "lê a própria linha" on public.subscriptions for select to authenticated
  using (user_id = (select auth.uid()));

-- Tabelas novas depois do segundo fator ganham a mesma política restritiva.
create policy "segundo fator" on public.features as restrictive to authenticated
