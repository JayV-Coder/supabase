create policy "segundo fator" on public.plans as restrictive to authenticated
  using ((select public.second_factor_ok())) with check ((select public.second_factor_ok()));
create policy "segundo fator" on public.plan_features as restrictive to authenticated
  using ((select public.second_factor_ok())) with check ((select public.second_factor_ok()));
create policy "segundo fator" on public.billing_customers as restrictive to authenticated
  using ((select public.second_factor_ok())) with check ((select public.second_factor_ok()));
create policy "segundo fator" on public.subscriptions as restrictive to authenticated
  using ((select public.second_factor_ok())) with check ((select public.second_factor_ok()));

-- Nenhuma destas tabelas é escrita direto pela API: o catálogo pelas RPCs do
-- admin, cliente e assinatura pelas funções do Stripe (service role).
revoke insert, update, delete, truncate on public.features, public.plans, public.plan_features, public.billing_customers, public.subscriptions from anon, authenticated;
revoke all on public.features, public.plans, public.plan_features, public.billing_customers, public.subscriptions from anon;

-- O app ouve a própria assinatura e o catálogo: o pagamento e a troca feita
-- pelo admin chegam sem reabrir a tela.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.subscriptions, public.features, public.plans, public.plan_features;
  end if;
end
$$;

-- 5. O que vale para quem chama. `past_due` ainda conta: o Stripe tenta de
-- novo por alguns dias antes de cancelar, e cortar na primeira falha do
-- cartão castiga quem só precisa trocá-lo.
create function public.my_plan() returns text language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select s.plan_key from public.subscriptions s join public.plans p on p.key = s.plan_key
      where s.user_id = auth.uid() and s.status in ('active', 'trialing', 'past_due')),
    (select p.key from public.plans p where p.is_default)
  );
$$;
revoke execute on function public.my_plan() from public, anon;
grant execute on function public.my_plan() to authenticated;

-- `{ plan, features, admin }`: os recursos ligados pelo admin que estão no
-- plano de quem chama. É o que o app e o núcleo leem.
create function public.my_features() returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'plan', public.my_plan(),
    'admin', coalesce(public.is_admin(), false),
    'features', coalesce((
      select jsonb_agg(f.key order by f.position, f.key)
      from public.features f join public.plan_features pf on pf.feature_key = f.key
      where f.enabled and pf.plan_key = public.my_plan()
    ), '[]'::jsonb)
  );
$$;
revoke execute on function public.my_features() from public, anon;
grant execute on function public.my_features() to authenticated;

-- 6. Escrita do admin.
create function public.admin_set_feature(feature text, on_off boolean) returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public.admin_require();
  update public.features set enabled = on_off, updated_by = auth.uid(), updated_at = now() where key = feature;
  if not found then raise exception 'admin.error.unknownFeature'; end if;
end;
$$;

-- Cria ou troca um plano inteiro: campos e recursos. `plan.features` é a
-- lista de chaves; chave fora do catálogo recusa tudo.
create function public.admin_save_plan(plan jsonb) returns void language plpgsql security definer set search_path = '' as $$
declare
  chosen text := plan->>'key';
  wanted text[];
begin
  perform public.admin_require();
  if jsonb_typeof(plan) is distinct from 'object' or jsonb_typeof(plan->'features') is distinct from 'array' then
    raise exception 'admin.error.planInvalid';
  end if;
  wanted := array(select distinct jsonb_array_elements_text(plan->'features'));
  if exists (select 1 from unnest(wanted) k where not exists (select 1 from public.features f where f.key = k)) then
    raise exception 'admin.error.unknownFeature';
  end if;
  begin
    -- Um padrão novo tira o posto do antigo antes de a linha nova entrar.
    if coalesce((plan->>'is_default')::boolean, false) then
      update public.plans set is_default = false where is_default and key <> chosen;
    end if;
    insert into public.plans (key, name, description, position, active, is_default, stripe_price_id, price_cents, currency, billing_interval, updated_by, updated_at)
    values (
      chosen, btrim(plan->>'name'), coalesce(plan->>'description', ''), coalesce((plan->>'position')::integer, 0),
      coalesce((plan->>'active')::boolean, true), coalesce((plan->>'is_default')::boolean, false),
      nullif(btrim(plan->>'stripe_price_id'), ''), (plan->>'price_cents')::integer, nullif(lower(btrim(plan->>'currency')), ''),
      nullif(plan->>'billing_interval', ''), auth.uid(), now()
    )
    on conflict (key) do update set
      name = excluded.name, description = excluded.description, position = excluded.position, active = excluded.active,
      is_default = excluded.is_default, stripe_price_id = excluded.stripe_price_id, price_cents = excluded.price_cents,
      currency = excluded.currency, billing_interval = excluded.billing_interval, updated_by = excluded.updated_by, updated_at = excluded.updated_at;
  exception
    when check_violation or not_null_violation or invalid_text_representation then raise exception 'admin.error.planInvalid';
    when unique_violation then raise exception 'admin.error.priceTaken';
  end;
  if not exists (select 1 from public.plans where is_default) then raise exception 'admin.error.default'; end if;
  delete from public.plan_features pf where pf.plan_key = chosen and not (pf.feature_key = any (wanted));
  insert into public.plan_features (plan_key, feature_key) select chosen, k from unnest(wanted) k on conflict do nothing;
end;
$$;

-- O padrão não sai, nem plano com assinatura de alguém: desative-o em vez de
-- apagar, e quem já assina segue até cancelar.
create function public.admin_delete_plan(plan text) returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public.admin_require();
  if exists (select 1 from public.plans where key = plan and is_default) then raise exception 'admin.error.default'; end if;
  if exists (select 1 from public.subscriptions where plan_key = plan) then raise exception 'admin.error.inUse'; end if;
  delete from public.plans where key = plan;
end;
$$;

-- Quantas contas assinam cada plano, para o admin decidir sem abrir o Stripe.
create function public.admin_plan_counts() returns table (plan_key text, subscribers bigint) language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.admin_require();
  return query select s.plan_key, count(*) from public.subscriptions s
    where s.status in ('active', 'trialing', 'past_due') group by s.plan_key;
end;
$$;

revoke execute on function public.admin_set_feature(text, boolean) from public, anon;
revoke execute on function public.admin_save_plan(jsonb) from public, anon;
revoke execute on function public.admin_delete_plan(text) from public, anon;
revoke execute on function public.admin_plan_counts() from public, anon;
grant execute on function public.admin_set_feature(text, boolean) to authenticated;
grant execute on function public.admin_save_plan(jsonb) to authenticated;
grant execute on function public.admin_delete_plan(text) to authenticated;
grant execute on function public.admin_plan_counts() to authenticated;

